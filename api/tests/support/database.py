"""Alembic and database helpers for tests."""

from __future__ import annotations

import re

from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from sqlalchemy import create_engine, make_url, text

from app.config import REPO_ROOT

ALEMBIC_INI = REPO_ROOT / "api" / "alembic.ini"


def alembic_config(url: str | None = None) -> Config:
    config = Config(str(ALEMBIC_INI))
    if url is not None:
        config.attributes["database_url"] = url
    # Leave pytest's logging alone.
    config.attributes["configure_logging"] = False
    return config


def head_revision() -> str:
    head = ScriptDirectory.from_config(alembic_config()).get_current_head()
    assert head is not None
    return head


def upgrade(url: str, revision: str = "head") -> None:
    command.upgrade(alembic_config(url), revision)


def downgrade(url: str, revision: str) -> None:
    command.downgrade(alembic_config(url), revision)


def check(url: str) -> None:
    """Raise ``AutogenerateDiffsDetected`` if the models and the schema disagree."""
    command.check(alembic_config(url))


def sibling_database_url(url: str, suffix: str) -> str:
    parsed = make_url(url)
    return parsed.set(database=f"{parsed.database}_{suffix}").render_as_string(hide_password=False)


def _database_name(url: str) -> str:
    """The database name from ``url``, checked so it can be interpolated into DDL."""
    name = make_url(url).database
    if not name or not re.fullmatch(r"[a-z_][a-z0-9_]*", name):
        raise ValueError(f"unsafe database name {name!r}")
    return name


def _run_autocommit(admin_url: str, *statements: str) -> None:
    engine = create_engine(admin_url, isolation_level="AUTOCOMMIT")
    try:
        with engine.connect() as connection:
            for statement in statements:
                connection.execute(text(statement))
    finally:
        engine.dispose()


def recreate_database(admin_url: str, target_url: str) -> None:
    """Drop and create the database named in ``target_url``, connecting via ``admin_url``."""
    name = _database_name(target_url)
    _run_autocommit(
        admin_url, f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)', f'CREATE DATABASE "{name}"'
    )


def drop_database(admin_url: str, target_url: str) -> None:
    name = _database_name(target_url)
    _run_autocommit(admin_url, f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)')
